export function translate(key: string, locale: UiLocale, values: Record<string, string | number> = {}): string {
  const normalized = key.replace(/\s+/g, " ").trim();
  const message = locale.startsWith("es") ? spanishMessages[normalized] ?? normalized : normalized;
  return message.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/g, (placeholder, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : placeholder);
}

// State notices can have been created before a language change. Resolve only
// known system messages, never arbitrary story content or workflow behavior.
const spanishNoticeKeys = new Map(Object.entries(spanishMessages).map(([key, value]) => [value, key]));
export function noticeKey(value: string): string {
  const key = value.replace(/\s+/g, " ").trim();
  return Object.prototype.hasOwnProperty.call(spanishMessages, key) ? key
    : spanishNoticeKeys.get(key) ?? "Something went wrong. Please try again.";
}
